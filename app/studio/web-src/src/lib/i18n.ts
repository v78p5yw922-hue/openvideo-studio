/**
 * i18n —— 极简实现：Zustand 保存语言，ZH / EN 两份字典。
 * 界面文案一律走 t('key') / tpl('key', vars)，不再硬编码中文。
 */

import { create } from 'zustand'

export type Lang = 'zh' | 'en'

interface I18nStore {
  lang: Lang
  setLang: (l: Lang) => void
  toggle: () => void
}

export const useI18n = create<I18nStore>((set, get) => ({
  lang: (typeof localStorage !== 'undefined' && (localStorage.getItem('ov-lang') as Lang)) || 'zh',
  setLang: (l) => {
    localStorage.setItem('ov-lang', l)
    set({ lang: l })
  },
  toggle: () => {
    const next: Lang = get().lang === 'zh' ? 'en' : 'zh'
    get().setLang(next)
  },
}))

/** 翻译函数：找不到时回退到 key 本身，方便发现漏配 */
export function t(key: string): string {
  const dict = useI18n.getState().lang === 'zh' ? ZH : EN
  return (dict as Record<string, string>)[key] ?? key
}

/** 模板填充：tpl('topbar.stats', { shots: 3, scenes: 4 }) */
export function tpl(key: string, vars?: Record<string, string | number>): string {
  let v = t(key)
  if (vars) {
    for (const [k, val] of Object.entries(vars)) {
      v = v.replace(new RegExp(`\\{${k}\\}`, 'g'), String(val))
    }
  }
  return v
}

